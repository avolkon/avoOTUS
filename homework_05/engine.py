"""
Модуль с датаклассом Engine для представления двигателя.
"""

from dataclasses import dataclass


@dataclass
class Engine:
    """
    Класс для представления двигателя транспортного средства.
    
    Использует декоратор @dataclass для автоматической генерации
    методов __init__, __repr__, __eq__ и других.
    
    Атрибуты:
        volume (float): Объем двигателя в литрах
        pistons (int): Количество поршней
    """
    
    volume: float
    """Объем двигателя в литрах (может быть дробным числом)"""
    
    pistons: int
    """Количество поршней (целое число)"""
    